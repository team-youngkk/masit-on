-- 고정 namespace의 seed UUID는 환경 간 동일하다. 기존 서울 ID는 생성하지 않는다.
INSERT INTO region (id, code, name, sort_order, active, administrative_code)
SELECT ('10000000-0000-4000-9000-00' || administrative_code)::uuid,
       'KR_' || administrative_code, name, sort_order, true, administrative_code
FROM region_seed_v20
WHERE parent_code IS NULL;

UPDATE region existing
SET administrative_code = seed.administrative_code,
    parent_id = province.id
FROM region_seed_v20 seed, region province
WHERE seed.parent_code = '1100000000'
  AND province.administrative_code = seed.parent_code
  AND existing.code LIKE 'SEOUL_%'
  AND existing.name = seed.name;

INSERT INTO region (id, code, name, sort_order, active, administrative_code, parent_id)
SELECT ('10000000-0000-4000-9000-00' || seed.administrative_code)::uuid,
       'KR_' || seed.administrative_code, seed.name, seed.sort_order, true,
       seed.administrative_code, province.id
FROM region_seed_v20 seed
JOIN region province ON province.administrative_code = seed.parent_code
WHERE seed.parent_code <> '1100000000';

-- 파생 부모 코드를 복합 FK로 묶어 다른 시도 연결·3단계·순환을 동시 쓰기에서도 거부한다.
-- parent_id만 검사하는 애플리케이션/트리거 검증에 의존하지 않는다.
ALTER TABLE region
    ALTER COLUMN administrative_code SET NOT NULL,
    ADD COLUMN parent_administrative_code varchar(10)
        GENERATED ALWAYS AS (
            CASE WHEN parent_id IS NULL THEN NULL
                 ELSE left(administrative_code, 2) || '00000000' END
        ) STORED,
    ADD CONSTRAINT uk_region__administrative_code UNIQUE (administrative_code),
    ADD CONSTRAINT uk_region__id_administrative_code UNIQUE (id, administrative_code),
    ADD CONSTRAINT uk_region__parent_name UNIQUE NULLS NOT DISTINCT (parent_id, name),
    ADD CONSTRAINT uk_region__parent_sort_order UNIQUE NULLS NOT DISTINCT (parent_id, sort_order),
    ADD CONSTRAINT ck_region__sort_order CHECK (sort_order > 0),
    ADD CONSTRAINT ck_region__administrative_code CHECK (administrative_code ~ '^[0-9]{5}00000$'),
    ADD CONSTRAINT ck_region__hierarchy CHECK (
        (parent_id IS NULL AND (right(administrative_code, 8) = '00000000'
            OR administrative_code = '3611000000'))
        OR
        (parent_id IS NOT NULL AND right(administrative_code, 8) <> '00000000'
            AND administrative_code <> '3611000000')
    ),
    ADD CONSTRAINT fk_region__province FOREIGN KEY (parent_id, parent_administrative_code)
        REFERENCES region (id, administrative_code) ON DELETE RESTRICT;
